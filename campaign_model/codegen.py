"""Generate the C++ view of the campaign contract: agents/AlphaMapAI/Schema.generated.h

	.venv/bin/python -m campaign_model.codegen

campaign_model/tests/test_contract.py fails if the checked-in header is out of date.
"""
from pathlib import Path

from . import constants as c
from .schema import HEADS, INPUTS, OUTPUTS, contract_hash

HEADER_PATH = Path(__file__).resolve().parent.parent / "agents" / "AlphaMapAI" / "Schema.generated.h"
DTYPES = {"int64": "INT64", "bool": "BOOL", "float32": "FLOAT32"}
MAX_RANK = 4


def _specs(specs):
	lines = []
	for s in specs:
		dims = list(s.shape) + [1] * (MAX_RANK - len(s.shape))
		lines.append(f'\tTensorSpec{{"{s.name}", DType::{DTYPES[s.dtype]}, {len(s.shape)}, {{{", ".join(map(str, dims))}}}, {s.fill}}},')
	return "\n".join(lines)


def _enum(name, members):
	body = "\n".join(f"\t{m.name} = {int(m)}," for m in members)
	return f"enum class {name} : int\n{{\n{body}\n}};"


def render():
	sizes = [
		"N_RESOURCES", "OWN_HEROES", "OTHER_HEROES", "N_HEROES", "OWN_TOWNS", "OTHER_TOWNS", "N_TOWNS", "ARMY_SLOTS", "ARMY_SLOT_CHOICES",
		"N_LEVELS", "N_WORN_SLOTS", "N_BACKPACK", "N_SECONDARY_SKILLS", "N_SPELLS", "N_PRIMARY", "N_BUILDINGS",
		"N_TAVERN", "WINDOW_RADIUS", "WINDOW", "N_HOLDERS", "OTHER_ARMY", "N_OPTIONS", "N_ADVENTURE_SPELLS",
		"N_BUY_ITEMS", "N_RECRUIT_AMOUNTS", "N_RECRUIT_TARGETS", "N_TRADE_AMOUNTS", "N_ARMY_AMOUNTS", "N_ACTION_TYPES", "N_VALUE_OFFSETS",
		"MAX_DECISIONS_PER_DAY", "OWNER_NONE", "OWNER_SELF", "DIMENSION_DOOR", "TOWN_PORTAL", "MEMORY_SLOTS", "MEMORY_WIDTH", "MEMORY_SCALE",
		"TILE_ON_MAP", "TILE_REVEALED", "TILE_BLOCKED", "TILE_VISITABLE", "TILE_WATER", "TILE_GUARDED",
		"TILE_VISITED_BY_PLAYER", "TILE_VISITED_BY_HERO", "TILE_EXACT_COUNT",
		"MAP_OBJECTS", "ARMED_OBJECTS", "MAP_GRID", "MAP_LEVELS", "MAP_TILES", "N_GRID_COUNTS", "OBJECT_VISITED_BY_PLAYER", "OBJECT_EXACT_COUNT", "OBJECT_GUARDED",
		"TRAVEL_GRID", "MAP_SIDE_MAX", "OBJECT_VOCAB", "OWNED_STACKS", "N_ARTIFACT_POSITIONS", "N_ARTIFACT_TARGETS", "N_MULTI",
	]
	heads = "\n".join(
		f"\t\tcase ActionType::{action.name}: return {{Out::{output}, In::{mask}}};" for action, (output, mask) in HEADS.items()
	)
	floats = lambda values: ", ".join(f"{v!r}" for v in values)  # noqa: E731
	return f"""// Generated by campaign_model/codegen.py from campaign_model/constants.py and schema.py. Do not edit.
#pragma once

#include <array>
#include <cstdint>
#include <utility>

namespace MapSchema
{{
constexpr int SCHEMA_VERSION = {c.SCHEMA_VERSION};
constexpr const char * CONTRACT_HASH = "{contract_hash()}";
constexpr const char * FAMILY = "campaign";

{chr(10).join(f"constexpr int {name} = {int(getattr(c, name))};" for name in sizes)}

{_enum("DecisionKind", c.DecisionKind)}

{_enum("ActionType", c.ActionType)}

{_enum("OptionKind", c.OptionKind)}

{_enum("ArmyAmount", c.ArmyAmount)}

{_enum("ArtifactTarget", c.ArtifactTarget)}

{_enum("MultiKind", c.MultiKind)}

{_enum("GridCount", c.GridCount)}

constexpr std::array<ActionType, {len(c.RESERVED_ACTION_TYPES)}> RESERVED_ACTION_TYPES = {{{", ".join(f"ActionType::{a.name}" for a in c.RESERVED_ACTION_TYPES)}}};
constexpr std::array<int, {len(c.TARGETED_SPELLS)}> TARGETED_SPELLS = {{{", ".join(map(str, c.TARGETED_SPELLS))}}};
constexpr std::array<int, N_BUY_ITEMS> BUY_ARTIFACTS = {{{", ".join(map(str, c.BUY_ARTIFACTS))}}};
constexpr std::array<double, N_RECRUIT_AMOUNTS> RECRUIT_FRACTIONS = {{{floats(c.RECRUIT_FRACTIONS)}}};
constexpr std::array<double, N_TRADE_AMOUNTS> TRADE_FRACTIONS = {{{floats(c.TRADE_FRACTIONS)}}};

enum class DType : int
{{
	INT64,
	BOOL,
	FLOAT32,
}};

/// One named tensor; dims exclude the leading batch dimension (always 1 on the C++ side), unused dims are 1
struct TensorSpec
{{
	const char * name;
	DType dtype;
	int rank;
	std::array<int64_t, {MAX_RANK}> dims;
	int64_t fill;

	constexpr int64_t size() const {{ return dims[0] * dims[1] * dims[2] * dims[3]; }}
}};

enum class In : int
{{
{chr(10).join(f"	{s.name}," for s in INPUTS)}
	COUNT
}};

constexpr std::array<TensorSpec, static_cast<int>(In::COUNT)> INPUTS = {{{{
{_specs(INPUTS)}
}}}};

enum class Out : int
{{
{chr(10).join(f"	{s.name}," for s in OUTPUTS)}
	COUNT
}};

constexpr std::array<TensorSpec, static_cast<int>(Out::COUNT)> OUTPUTS = {{{{
{_specs(OUTPUTS)}
}}}};

/// The table (output) and its legality mask (input) of an action type; END has none
constexpr std::pair<Out, In> head(ActionType type)
{{
	switch(type)
	{{
{heads}
		default: return {{Out::COUNT, In::COUNT}};
	}}
}}
}}
"""


def main():
	HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
	HEADER_PATH.write_text(render())
	print(f"wrote {HEADER_PATH}")


if __name__ == "__main__":
	main()
