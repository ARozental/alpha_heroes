"""Generate the C++ view of the contract: agents/AlphaBattleAI/Schema.generated.h

	.venv/bin/python -m battle_model.codegen

tests/test_codegen.py fails if the checked-in header is out of date.
"""
from pathlib import Path

from . import constants as c
from . import reward as r
from .schema import INPUTS, OUTPUTS, contract_hash

HEADER_PATH = Path(__file__).resolve().parent.parent / "agents" / "AlphaBattleAI" / "Schema.generated.h"
DTYPES = {"int64": "INT64", "bool": "BOOL", "float32": "FLOAT32"}


def _specs(specs):
	lines = []
	for s in specs:
		dims = list(s.shape) + [0] * (2 - len(s.shape))
		lines.append(f'\tTensorSpec{{"{s.name}", DType::{DTYPES[s.dtype]}, {len(s.shape)}, {{{dims[0]}, {dims[1]}}}, {s.fill}}},')
	return "\n".join(lines)


def render():
	sizes = [
		("N_HEXES", c.N_HEXES),
		("FIELD_WIDTH", c.FIELD_WIDTH),
		("MAX_UNITS", c.MAX_UNITS),
		("UNITS_PER_SIDE", c.UNITS_PER_SIDE),
		("MAX_EFFECTS", c.MAX_EFFECTS),
		("N_SIDES", c.N_SIDES),
		("N_SPELLS", c.N_SPELLS),
		("N_SECONDARY_SKILLS", c.N_SECONDARY_SKILLS),
		("MAX_RETALIATIONS", c.MAX_RETALIATIONS),
		("N_ACTION_TYPES", c.N_ACTION_TYPES),
	]
	action_types = "\n".join(f"\t{a.name} = {int(a)}," for a in c.ActionType)
	second_cases = "\n".join(f"\t\tcase {spell}: return TargetKind::{kind.name};" for spell, kind in sorted(c.SECOND_TARGET_KIND.items()))
	reserved = ", ".join(f"ActionType::{a.name}" for a in c.RESERVED_ACTION_TYPES)
	outcomes = "\n".join(f"\t{o.name} = {int(o)}," for o in r.Outcome)
	outcome_terms = ", ".join(repr(r.OUTCOME_TERM[o]) for o in r.Outcome)
	survives = ", ".join("true" if o in r.HERO_SURVIVES else "false" for o in r.Outcome)
	prices = ", ".join(str(price) for price in r.RESOURCE_PRICES.values())
	config = r.RewardConfig()
	return f"""// Generated by battle_model/codegen.py from battle_model/constants.py and schema.py. Do not edit.
#pragma once

#include <array>
#include <cstdint>

namespace AlphaSchema
{{
constexpr int SCHEMA_VERSION = {c.SCHEMA_VERSION};
constexpr const char * CONTRACT_HASH = "{contract_hash()}";

{chr(10).join(f"constexpr int {name} = {value};" for name, value in sizes)}

enum class ActionType : int
{{
{action_types}
}};

constexpr std::array<ActionType, {len(c.RESERVED_ACTION_TYPES)}> RESERVED_ACTION_TYPES = {{{reserved}}};

enum class TargetKind : int
{{
	NONE = 0,
	UNIT = 1,
	HEX = 2,
}};

/// Kind of the second destination of a spell, NONE for single-destination spells
constexpr TargetKind secondTargetKind(int spell)
{{
	switch(spell)
	{{
{second_cases}
		default: return TargetKind::NONE;
	}}
}}

enum class DType : int
{{
	INT64,
	BOOL,
	FLOAT32,
}};

/// One named tensor; dims exclude the leading batch dimension (always 1 on the C++ side)
struct TensorSpec
{{
	const char * name;
	DType dtype;
	int rank;
	std::array<int64_t, 2> dims;
	int64_t fill;
}};

enum class In : int
{{
{chr(10).join(f"	{s.name}," for s in INPUTS)}
	COUNT
}};

constexpr std::array<TensorSpec, static_cast<int>(In::COUNT)> INPUTS = {{{{
{_specs(INPUTS)}
}}}};

enum class Out : int
{{
{chr(10).join(f"	{s.name}," for s in OUTPUTS)}
	COUNT
}};

constexpr std::array<TensorSpec, static_cast<int>(Out::COUNT)> OUTPUTS = {{{{
{_specs(OUTPUTS)}
}}}};

// The terminal reward, battle_model/reward.py (computed in Reward.h)
enum class Outcome : int
{{
{outcomes}
}};

constexpr std::array<double, {len(r.Outcome)}> OUTCOME_TERM = {{{outcome_terms}}};
constexpr std::array<bool, {len(r.Outcome)}> HERO_SURVIVES = {{{survives}}};
constexpr int MAX_PENALIZED_ROUNDS = {r.MAX_PENALIZED_ROUNDS};
constexpr double ROUND_PENALTY = {config.round_penalty!r};
constexpr double MANA_PENALTY = {config.mana_penalty!r};
constexpr int HERO_HIRE_COST = {r.HERO_HIRE_COST};
/// Gold value of one unit of each resource, in VCMI's order: {", ".join(r.RESOURCE_PRICES)}
constexpr std::array<int, {len(r.RESOURCE_PRICES)}> RESOURCE_PRICES = {{{prices}}};
}}
"""


def main():
	HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
	HEADER_PATH.write_text(render())
	print(f"wrote {HEADER_PATH}")


if __name__ == "__main__":
	main()
